#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";
import { loadLocalEnv } from "./private-env.mjs";

loadLocalEnv();

const tableOrder = [
  ["families", "id"],
  ["family_settings", "family_id"],
  ["children", "id"],
  ["child_intake_profiles", "child_id"],
  ["calendar_events", "id"],
  ["calendar_event_children", "event_id,child_id"],
  ["learning_records", "id"],
  ["education_goals", "id"],
  ["milestones", "id"],
  ["resources", "id"],
  ["learning_materials", "id"],
  ["self_evaluations", "id"],
  ["tutor_feedback", "id"]
];

const requiredTables = tableOrder.map(([tableName]) => tableName);

function getArgValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function requireEnv(name) {
  const value = process.env[name];
  if (!value) {
    throw new Error(`${name} is required`);
  }

  return value;
}

function normalizeBackup(payload) {
  if (payload?.tables) return payload;
  if (payload?.data?.tables) return payload.data;
  throw new Error("Backup JSON must contain a tables object from /api/private/export.");
}

function normalizeStorageManifest(payload) {
  if (!payload || payload.version !== 1 || !Array.isArray(payload.objects)) {
    throw new Error("storage-manifest.json must be generated by private:backup-storage.");
  }

  return payload;
}

async function assertStorageManifest(backup, manifestPath) {
  if (!manifestPath) {
    console.log("- storage manifest: not provided");
    return;
  }

  const manifest = normalizeStorageManifest(JSON.parse(await readFile(manifestPath, "utf8")));
  const objectPaths = new Set(manifest.objects.map((object) => object.path).filter(Boolean));
  const manifestObjectsByPath = new Map(manifest.objects.map((object) => [object.path, object]));
  const backupDir = path.dirname(manifestPath);
  const missingPaths = (backup.tables.learning_materials ?? [])
    .map((material) => material.storage_path)
    .filter((storagePath) => storagePath && !objectPaths.has(storagePath));

  if (missingPaths.length > 0) {
    throw new Error(`Storage manifest is missing ${missingPaths.length} learning material file(s): ${missingPaths.slice(0, 5).join(", ")}`);
  }

  for (const object of manifest.objects) {
    if (!object?.path) continue;
    const body = await readFile(path.join(backupDir, "files", object.path));
    if (object.sha256) {
      const sha256 = createHash("sha256").update(body).digest("hex");
      if (sha256 !== object.sha256) {
        throw new Error(`Storage backup checksum mismatch: ${object.path}`);
      }
    }
  }

  for (const material of backup.tables.learning_materials ?? []) {
    if (!material.storage_path) continue;
    const object = manifestObjectsByPath.get(material.storage_path);
    if (object?.backupSize != null && material.file_size != null && Number(material.file_size) !== Number(object.backupSize)) {
      throw new Error(`Storage metadata size mismatch: ${material.storage_path}`);
    }
  }

  console.log(`- storage manifest: verified ${objectPaths.size} object(s)`);
}

async function restoreTable(supabase, tableName, onConflict, rows, dryRun) {
  if (!Array.isArray(rows) || rows.length === 0) {
    console.log(`- ${tableName}: 0 rows`);
    return;
  }

  if (dryRun) {
    console.log(`- ${tableName}: ${rows.length} rows ready`);
    return;
  }

  const { error } = await supabase.from(tableName).upsert(rows, {
    onConflict,
    ignoreDuplicates: false
  });

  if (error) {
    throw new Error(`${tableName}: ${error.message}`);
  }

  console.log(`- ${tableName}: restored ${rows.length} rows`);
}

async function assertSchema(supabase, dryRun) {
  if (dryRun) {
    console.log("- schema: skipped in dry run");
    return;
  }

  for (const tableName of requiredTables) {
    const { error } = await supabase.from(tableName).select("*").limit(0);
    if (error) {
      throw new Error(`Table "${tableName}" is not ready. Run docs/private-supabase-schema.sql before restoring.`);
    }
  }

  console.log("- schema: verified");
}

async function main() {
  const filePath = getArgValue("--file");
  const storageManifestPath = getArgValue("--storage-manifest");
  const dryRun = process.argv.includes("--dry-run");

  if (!filePath) {
    throw new Error("Usage: npm run private:restore -- --file ./backup.json [--storage-manifest ./private-storage-backup/storage-manifest.json] [--dry-run]");
  }

  const raw = await readFile(filePath, "utf8");
  const backup = normalizeBackup(JSON.parse(raw));
  const supabase = dryRun
    ? null
    : createClient(requireEnv("NEXT_PUBLIC_SUPABASE_URL"), requireEnv("SUPABASE_SERVICE_ROLE_KEY"), {
        auth: {
          persistSession: false,
          autoRefreshToken: false
        }
      });

  console.log(dryRun ? "Dry run restore plan:" : "Restoring private family backup:");
  console.log(`Family: ${backup.familyId ?? "unknown"}`);
  console.log(`Exported at: ${backup.exportedAt ?? "unknown"}`);

  await assertSchema(supabase, dryRun);
  await assertStorageManifest(backup, storageManifestPath);

  for (const [tableName, onConflict] of tableOrder) {
    await restoreTable(supabase, tableName, onConflict, backup.tables[tableName], dryRun);
  }

  console.log("Done. File bodies are not restored by this script; Storage paths are preserved in metadata.");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
