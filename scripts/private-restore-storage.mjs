#!/usr/bin/env node

import { readFile } from "node:fs/promises";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";
import { loadLocalEnv } from "./private-env.mjs";

loadLocalEnv();

function getArgValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function requireEnv(name) {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is required`);
  return value;
}

function isHelp() {
  return process.argv.includes("--help") || process.argv.includes("-h");
}

function usage() {
  console.log("Usage: npm run private:restore-storage -- --dir ./private-storage-backup [--dry-run]");
  console.log("");
  console.log("The directory must contain:");
  console.log("- storage-manifest.json");
  console.log("- files/<storage_path>");
  console.log("");
  console.log("Required env:");
  console.log("- NEXT_PUBLIC_SUPABASE_URL");
  console.log("- SUPABASE_SERVICE_ROLE_KEY");
  console.log("- SUPABASE_LEARNING_MATERIALS_BUCKET, defaults to manifest bucket or learning-materials");
}

function normalizeManifest(payload) {
  if (!payload || payload.version !== 1 || !Array.isArray(payload.objects)) {
    throw new Error("storage-manifest.json must be generated by private:backup-storage.");
  }

  return payload;
}

async function restoreObject(supabase, bucket, backupDir, object, dryRun) {
  const sourcePath = path.join(backupDir, "files", object.path);
  const body = await readFile(sourcePath);
  const mimetype = object.mimetype || "application/octet-stream";

  if (dryRun) {
    console.log(`- ${object.path}: ${body.length} bytes ready`);
    return;
  }

  const { error } = await supabase.storage.from(bucket).upload(object.path, body, { contentType: mimetype, upsert: true });
  if (error) throw new Error(`${object.path}: ${error.message}`);
  console.log(`- ${object.path}: restored ${body.length} bytes`);
}

async function main() {
  if (isHelp()) {
    usage();
    return;
  }

  const backupDir = getArgValue("--dir");
  const dryRun = process.argv.includes("--dry-run");
  if (!backupDir) throw new Error("Usage: npm run private:restore-storage -- --dir ./private-storage-backup [--dry-run]");

  const manifestPath = path.join(backupDir, "storage-manifest.json");
  const manifest = normalizeManifest(JSON.parse(await readFile(manifestPath, "utf8")));
  const bucket = process.env.SUPABASE_LEARNING_MATERIALS_BUCKET || manifest.bucket || "learning-materials";
  const supabase = dryRun
    ? null
    : createClient(requireEnv("NEXT_PUBLIC_SUPABASE_URL"), requireEnv("SUPABASE_SERVICE_ROLE_KEY"), {
        auth: {
          persistSession: false,
          autoRefreshToken: false
        }
      });

  console.log(dryRun ? "Dry run storage restore plan:" : "Restoring private Storage backup:");
  console.log(`Bucket: ${bucket}`);
  console.log(`Objects: ${manifest.objects.length}`);

  for (const object of manifest.objects) {
    if (!object?.path || typeof object.path !== "string") {
      throw new Error("Manifest object is missing path.");
    }

    await restoreObject(supabase, bucket, backupDir, object, dryRun);
  }

  console.log("Done. Validate signed downloads from the app after restoring database metadata and Storage files.");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
